#!/usr/bin/env python3
"""
Turn tools/lobby/layout.json (written by the Blender generator) into game data:

  * packages/shared/src/constants.ts  -> TOWN_OBSTACLES entries (collision circles for buildings, trees, props)
  * apps/client/src/scene/lobbyLayout.ts -> lights / glow halos / chimney smoke / lamp positions

Usage (repo root):  python3 tools/lobby/gen_game_data.py
Re-run after every Blender export so collision + lights always match the model.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
LAYOUT = json.load(open(os.path.join(ROOT, 'tools/lobby/layout.json')))

# ---------------------------------------------------------------- collision (shared)
cols = LAYOUT['colliders']
groups = {}
for c in cols:
    k = c['n']
    if k in ('fountain',):
        g = 'Town-centre fountain'
    elif k.startswith('PortalGate'):
        g = 'Portal gate pillars'
    elif k in ('pine1', 'pine2', 'pine3', 'oak1', 'oak2', 'oak3', 'autumn', 'autumn2', 'blossom1', 'blossom2', 'birch1', 'birch2', 'rock'):
        g = 'Trees & rocks (trunk / boulder footprint)'
    else:
        g = 'Buildings, stalls & props'
    groups.setdefault(g, []).append(c)
lines = []
for g, items in groups.items():
    lines.append(f'  // {g}.')
    for c in items:
        lines.append(f"  {{ x: {c['x']}, z: {c['z']}, radius: {c['r']} }},")
body = '\n'.join(lines)

p = os.path.join(ROOT, 'packages/shared/src/constants.ts')
s = open(p).read()
start = s.index('export const TOWN_OBSTACLES')
arr_start = s.index('...castleColliders(),', start) + len('...castleColliders(),')
arr_end = s.index('\n];', arr_start)
s = s[:arr_start] + '\n' + body + s[arr_end:]
open(p, 'w').write(s)
print('colliders:', len(cols))

# ---------------------------------------------------------------- client layout
def r(v):
    return round(v, 2)


out = []
out.append('// GENERATED by tools/lobby/gen_game_data.py from tools/lobby/layout.json — do not edit by hand.')
out.append('// Positions are game-world coordinates (x, y-up, z).')
out.append('')
out.append('export interface LobbyLight {')
out.append('  name: string;')
out.append('  pos: [number, number, number];')
out.append('  color: string;')
out.append('  intensity: number;')
out.append('  distance: number;')
out.append('}')
out.append('')
out.append('export const LOBBY_LIGHTS: readonly LobbyLight[] = [')
for l in LAYOUT['lights']:
    out.append(f"  {{ name: '{l['n']}', pos: [{r(l['x'])}, {r(l['y'])}, {r(l['z'])}], color: '{l['color']}', intensity: {l['i']}, distance: {l['d']} }},")
out.append('];')
out.append('')
out.append('/** Soft additive glow sprites (lanterns, braziers, forge, crystal). `size` is the world-space diameter. */')
out.append('export const LOBBY_HALOS: readonly { pos: [number, number, number]; color: string; size: number }[] = [')
for h in LAYOUT['halos']:
    out.append(f"  {{ pos: [{r(h['x'])}, {r(h['y'])}, {r(h['z'])}], color: '{h['color']}', size: {r(h['s'])} }},")
for l in LAYOUT['lamps']:
    out.append(f"  {{ pos: [{r(l['x'])}, {r(l['y'])}, {r(l['z'])}], color: '#ffc27a', size: 1.5 }},")
out.append('];')
out.append('')
out.append('/** Chimney tops: smoke rises from here. */')
out.append('export const LOBBY_CHIMNEYS: readonly [number, number, number][] = [')
for sm in LAYOUT['smoke']:
    out.append(f"  [{r(sm['x'])}, {r(sm['y'])}, {r(sm['z'])}],")
out.append('];')
out.append('')
fo = LAYOUT['fountain']
out.append('/** Fountain water spec (levels are world-space y; radii are metres from the fountain centre). */')
out.append('export const LOBBY_FOUNTAIN = {')
out.append(f"  center: [{fo['center'][0]}, {fo['center'][1]}] as [number, number],")
out.append('  spouts: [' + ', '.join(f"[{s[0]}, {s[1]}]" for s in fo['spouts']) + '] as [number, number][],')
out.append(f"  basinY: {fo['basin_y']}, basinR: {fo['basin_r']},")
out.append(f"  tier1Y: {fo['t1_y']}, tier1R: {fo['t1_r']},")
out.append(f"  tier2Y: {fo['t2_y']}, tier2R: {fo['t2_r']},")
out.append('};')
out.append('')
open(os.path.join(ROOT, 'apps/client/src/scene/lobbyLayout.ts'), 'w').write('\n'.join(out))
print('lights', len(LAYOUT['lights']), 'halos', len(LAYOUT['halos']) + len(LAYOUT['lamps']), 'chimneys', len(LAYOUT['smoke']))
